# ------------------------------------------------------------------------------
# Command Validation
# ------------------------------------------------------------------------------

command_exists() {

	command -v "$1" >/dev/null 2>&1

}

require_command() {

	local cmd="$1"

	if ! command_exists "$cmd"; then

		fatal "Required command not found: ${cmd}"

	fi

}

# ------------------------------------------------------------------------------
# Internet
# ------------------------------------------------------------------------------

check_internet() {

	command_exists ping || return 1

	case "$(uname -s)" in
	Darwin)
		ping -c 1 -t 1 1.1.1.1 >/dev/null 2>&1
		;;
	*)
		ping -c 1 -W 1 1.1.1.1 >/dev/null 2>&1
		;;
	esac

}

require_internet() {

	if ! check_internet; then

		fatal "Internet connection required."

	fi

}

# ------------------------------------------------------------------------------
# Termux
# ------------------------------------------------------------------------------

is_termux() {

	[[ -n "${TERMUX_VERSION:-}" ]]

}

require_termux() {

	if ! is_termux; then

		fatal "This project must be executed inside Termux."

	fi

}

# ------------------------------------------------------------------------------
# Android
# ------------------------------------------------------------------------------

is_android() {

	[[ -d "/system" ]]

}

# ------------------------------------------------------------------------------
# Architecture
# ------------------------------------------------------------------------------

architecture() {

	printf "%s\n" "${SYSTEM_ARCH:-$(uname -m)}"

}

is_arm64() {

	[[ "${SYSTEM_ARCH:-$(uname -m)}" == "aarch64" ]]

}

is_x86_64() {

	[[ "${SYSTEM_ARCH:-$(uname -m)}" == "x86_64" ]]

}

# ------------------------------------------------------------------------------
# Files
# ------------------------------------------------------------------------------

file_exists() {

	[[ -f "$1" ]]

}

directory_exists() {

	[[ -d "$1" ]]

}

# ------------------------------------------------------------------------------
# Variables
# ------------------------------------------------------------------------------

variable_is_set() {

	[[ -n "${!1:-}" ]]

}

# ------------------------------------------------------------------------------
# User Confirmation
# ------------------------------------------------------------------------------

confirm() {

	local answer

	read -rp "$1 [y/N]: " answer

	[[ "$answer" =~ ^[Yy]$ ]]

}
